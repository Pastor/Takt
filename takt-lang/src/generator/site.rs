//! Позиция текущего оператора при генерации — общий носитель (фича 0277).
//!
//! # Зачем
//!
//! Отказ цели указывал не туда. Замер 2026-08-19 на `res := mem[1:2];`
//! (строка 7):
//!
//! | Цель | Координата отказа |
//! |---|---|
//! | `c` | **`1:1`** — строка, где объявлена `mem` |
//! | `rust`, `st` | **нет вовсе**: отказ строится с `Location::Codegen` |
//!
//! Причина у обоих одна: позиции **употребления** у `ExpressionNode` нет ни у
//! одного варианта. Решение 0056 сознательно не стало заводить её полем — это
//! значило бы тащить координату через ~40 вариантов перечисления, где она
//! никому не нужна; там, где выражение позицию всё же выводит, оно берёт её у
//! **объявления** операнда.
//!
//! Фича [0264](../../../docs/features/0264-body-judge-usage-position.md) дала
//! позицию **оператору** (`StatementNode::Expression`). Печать выражения всегда
//! идёт внутри оператора, поэтому цели могут взять координату оттуда — не меняя
//! ни `ExpressionNode`, ни сигнатуры рекурсивных печатников.
//!
//! # Как
//!
//! Печатник операторов объявляет место (`enter`), печатник выражений
//! спрашивает его (`current`) — но **только** когда своей позиции у отказа нет.
//! Носитель живёт в карте цели, которая и так доходит до каждого печатника.
//!
//! ⚠️ **Это изменяемое состояние на время генерации**, и потому оно названо и
//! ограничено: `enter` зовёт **только** печать операторов, а `current`
//! возвращает `Location::Builtin`, пока ни один оператор не начат (генерация
//! объявлений, инициализаторов, заголовков).
//!
//! ⚠️ **Носитель один на все цели и потоковый** (фича 0308). Прежде он был
//! полем карты цели `c` — и остальные три цели воспользоваться им не могли:
//! их конструкторы отказов (`rust_expr::unsupported`, четыре копии
//! `unsupported` у `st`, отказы `sv`) — свободные функции без доступа к
//! контексту, а протаскивать карту через полсотни вызовов значило бы менять
//! сигнатуры ради координаты. Замер 2026-08-20 на `res := mem[1:2];`: цель `c`
//! указывала строку 10, а `rust`, `st` и `sv` печатали отказ **без позиции
//! вовсе**.
//!
//! ⚠️ Состояние **потоковое**, и это не украшение: тесты идут параллельно
//! (инвариант 0190), а генерация внутри потока однопоточна по построению — одна
//! цель, один проход.
//!
//! ⚠️ **Сброс обязателен на входе в генерацию** ([`reset`]): позиция последнего
//! оператора пережила бы вызов и досталась бы **следующей** генерации в том же
//! потоке — то есть отказ вне операторов получил бы координату из чужого файла.
//! Это ровно та ложная координата, от которой ушли 0264 и 0276.

use crate::diagnostics::Location;
use std::cell::Cell;

thread_local! {
    /// Позиция оператора, который печатается сейчас, — одна на поток.
    static SITE: Cell<Location> = const { Cell::new(Location::Builtin) };
}

/// Объявляет начало печати оператора. Зовёт **только** печатник операторов.
pub(crate) fn enter(loc: Location) {
    SITE.with(|site| site.set(loc));
}

/// Позиция текущего оператора; `Location::Builtin`, если оператор не начат.
pub(crate) fn current() -> Location {
    SITE.with(Cell::get)
}

/// Позиция для отказа цели: **оператор**, если он начат, иначе — своя.
///
/// ⚠️ Порядок именно такой, и это следствие замера. У выражения «своей»
/// позиции не бывает: `ExpressionNode::loc()` выводит её из **объявлений**
/// операндов, поэтому `res := mem[1:2];` в строке 10 давал координату строки
/// 1 — места, где объявлена `mem`. Такая координата не «менее точна», она
/// **указывает не туда**, и предпочитать её позиции оператора нельзя.
pub(crate) fn at(own: Location) -> Location {
    match current() {
        Location::Builtin => own,
        statement => statement,
    }
}

/// Забывает начатый оператор. Зовётся на входе в генерацию.
///
/// ⚠️ Без сброса позиция пережила бы вызов: следующая генерация в том же
/// потоке начиналась бы с координаты чужого файла, и отказ вне операторов
/// указывал бы туда — ложь достовернее молчания (класс 0264).
pub(crate) fn reset() {
    SITE.with(|site| site.set(Location::Builtin));
}

#[cfg(test)]
mod tests {
    use super::*;

    /// ⚠️ Тесты трогают **потоковый** носитель, поэтому каждый начинается со
    /// сброса: харнесс Rust гоняет тесты одного файла в разных потоках, но
    /// порядок внутри потока не задан, и оставленная позиция «протекла» бы в
    /// соседний тест.
    fn fresh() {
        reset();
    }

    #[test]
    fn empty_site_reports_builtin() {
        fresh();
        assert!(matches!(current(), Location::Builtin));
    }

    /// Позиция оператора вытесняет выведенную из объявления — в этом суть.
    #[test]
    fn statement_position_wins_inside_a_statement() {
        fresh();
        enter(Location::Source(0, 100, 110));
        for own in [
            Location::Codegen,
            Location::Builtin,
            // Позиция объявления операнда: выглядит настоящей и указывает не туда.
            Location::Source(0, 5, 7),
        ] {
            assert!(
                matches!(at(own), Location::Source(0, 100, 110)),
                "внутри оператора координата берётся у него, а не у {own:?}"
            );
        }
    }

    /// Вне оператора остаётся своя позиция — там она настоящая.
    #[test]
    fn outside_a_statement_own_position_remains() {
        fresh();
        assert!(matches!(
            at(Location::Source(0, 5, 7)),
            Location::Source(0, 5, 7)
        ));
        assert!(matches!(at(Location::Codegen), Location::Codegen));
    }

    /// Сброс забывает начатый оператор: иначе координата протекла бы в
    /// следующую генерацию того же потока.
    #[test]
    fn reset_forgets_the_statement() {
        fresh();
        enter(Location::Source(0, 100, 110));
        reset();
        assert!(matches!(at(Location::Codegen), Location::Codegen));
    }
}
