//! Позиция текущего оператора при генерации — общий носитель (фича 0277).
//!
//! # Зачем
//!
//! Отказ цели указывал не туда. Замер 2026-08-19 на `res := mem[1:2];`
//! (строка 7):
//!
//! | Цель | Координата отказа |
//! |---|---|
//! | `c` | **`1:1`** — строка, где объявлена `mem` |
//! | `rust`, `st` | **нет вовсе**: отказ строится с `Location::Codegen` |
//!
//! Причина у обоих одна: позиции **употребления** у `ExpressionNode` нет ни у
//! одного варианта. Решение 0056 сознательно не стало заводить её полем — это
//! значило бы тащить координату через ~40 вариантов перечисления, где она
//! никому не нужна; там, где выражение позицию всё же выводит, оно берёт её у
//! **объявления** операнда.
//!
//! Фича [0264](../../../docs/features/0264-body-judge-usage-position.md) дала
//! позицию **оператору** (`StatementNode::Expression`). Печать выражения всегда
//! идёт внутри оператора, поэтому цели могут взять координату оттуда — не меняя
//! ни `ExpressionNode`, ни сигнатуры рекурсивных печатников.
//!
//! # Как
//!
//! Печатник операторов объявляет место (`enter`), печатник выражений
//! спрашивает его (`current`) — но **только** когда своей позиции у отказа нет.
//! Носитель живёт в карте цели, которая и так доходит до каждого печатника.
//!
//! ⚠️ **Это изменяемое состояние на время генерации**, и потому оно одно на
//! цель, названо и ограничено: `enter` зовёт **только** печать операторов, а
//! `current` возвращает `Location::Builtin`, пока ни один оператор не начат
//! (генерация объявлений, инициализаторов, заголовков).
//!
//! ⚠️ Генерация **однопоточна** по построению (одна цель — один проход), и
//! `Cell` этого достаточно; разделяемого доступа здесь нет.

use crate::diagnostics::Location;
use std::cell::Cell;

/// Позиция оператора, который печатается сейчас.
///
/// ⚠️ Начальное значение — `Location::Builtin`, а **не** `Location::default()`:
/// умолчание у позиции есть `Source(0, 0, 0)`, то есть «начало первого файла»
/// — ровно та ложная координата, от которой уходят эта фича и 0276.
#[derive(Debug)]
pub(crate) struct StatementSite {
    current: Cell<Location>,
}

impl Default for StatementSite {
    fn default() -> Self {
        Self {
            current: Cell::new(Location::Builtin),
        }
    }
}

impl StatementSite {
    /// Объявляет начало печати оператора. Зовёт **только** печатник операторов.
    pub(crate) fn enter(&self, loc: Location) {
        self.current.set(loc);
    }

    /// Позиция текущего оператора; `Location::Builtin`, если оператор не начат.
    pub(crate) fn current(&self) -> Location {
        self.current.get()
    }

    /// Позиция для отказа цели: **оператор**, если он начат, иначе — своя.
    ///
    /// ⚠️ Порядок именно такой, и это следствие замера. У выражения «своей»
    /// позиции не бывает: `ExpressionNode::loc()` выводит её из **объявлений**
    /// операндов, поэтому `res := mem[1:2];` в строке 7 давал координату
    /// строки 1 — места, где объявлена `mem`. Такая координата не «менее
    /// точна», она **указывает не туда**, и предпочитать её позиции оператора
    /// нельзя.
    ///
    /// Вне операторов (объявления, инициализаторы, заголовки) оператор не
    /// начат, `current()` даёт `Builtin`, и остаётся своя позиция — там она
    /// настоящая.
    pub(crate) fn at(&self, own: Location) -> Location {
        match self.current() {
            Location::Builtin => own,
            statement => statement,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_site_reports_builtin() {
        let site = StatementSite::default();
        assert!(matches!(site.current(), Location::Builtin));
    }

    /// Позиция оператора вытесняет выведенную из объявления — в этом суть.
    #[test]
    fn statement_position_wins_inside_a_statement() {
        let site = StatementSite::default();
        site.enter(Location::Source(0, 100, 110));
        for own in [
            Location::Codegen,
            Location::Builtin,
            // Позиция объявления операнда: выглядит настоящей и указывает не туда.
            Location::Source(0, 5, 7),
        ] {
            assert!(
                matches!(site.at(own), Location::Source(0, 100, 110)),
                "внутри оператора координата берётся у него, а не у {own:?}"
            );
        }
    }

    /// Вне оператора остаётся своя позиция — там она настоящая.
    #[test]
    fn outside_a_statement_own_position_remains() {
        let site = StatementSite::default();
        assert!(matches!(
            site.at(Location::Source(0, 5, 7)),
            Location::Source(0, 5, 7)
        ));
        assert!(matches!(site.at(Location::Codegen), Location::Codegen));
    }
}
