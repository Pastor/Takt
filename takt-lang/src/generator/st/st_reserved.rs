//! Проверка идентификаторов на столкновение со стандартной библиотекой и
//! ключевыми словами IEC 61131-3 — диагностика `ST-014` (фича 0065, задача
//! 0065-02).
//!
//! ## Зачем
//!
//! Пространство имён IEC **плоское и общее со стандартной библиотекой**, а
//! идентификаторы **регистронезависимы**. Идентификатор, совпавший (без учёта
//! регистра) со стандартной функцией (`LEFT`, `ABS`, `MIN`, `CONCAT`…) или
//! ключевым словом (`STEP`, `ACTION`, `EXIT`…), `iec2c` отвергает — но
//! **обманчиво**: на `var left: u8` он отвечает `invalid located variable
//! declaration`, указывая на `AT %…`, которых в объявлении **нет вовсе**. По
//! тексту ошибки причину не найти. `ST-014` называет её прямо (прецедент —
//! `SV-012` цели `sv`).
//!
//! ## Список — только ПРОВЕРЕННОЕ пробой
//!
//! ⚠️ Каждое имя ниже **отвергается `iec2c`** — проверено прогоном
//! `var <имя>: u8` через MatIEC (2026-07-18). Это существенно: список нельзя
//! пополнять по памяти. `action` MatIEC отвергает (SFC-ключевое слово), тогда
//! как «здравый смысл» счёл бы его обычным словом; наоборот, `remaining`,
//! `count`, `mode`, `command` — **приняты** (в списке их быть не должно).
//!
//! **Полнота не критична для худшего случая** (ADR 0065): структурный дефект
//! (склейка одноимённых `fn`) закрывает префиксация POU
//! ([0065-01](../../../../docs/development/0065-01-prefix-pou.md)) **независимо**
//! от этого списка; пропущенное здесь имя поймает `iec2c` — громко, пусть и
//! обманчиво. Список **улучшает диагностику**, а не является единственной
//! защитой. Поэтому в него включено только доказанно-отвергаемое: ложное
//! срабатывание (запрет имени, которое MatIEC принимает) было бы **хуже**
//! статус-кво — оно сломало бы валидную модель, которую сегодня `iec2c`
//! собирает.
//!
//! ## Где проверяется
//!
//! Проверка стоит **в точках эмиссии** (как `check_sv_name`), а не общим
//! проходом по дереву: так проверяется ровно то, что попадёт в `.st`.
//! Неиспользуемая переменная фильтруется генератором и в вывод не идёт —
//! `iec2c` её тоже не увидит, поэтому и `ST-014` на неё срабатывать не должен
//! (иначе `elevator.takt`, где `var action: Action` объявлен, но не используется,
//! перестал бы собираться — регресс).

use crate::diagnostics::{Diagnostic, Location};

/// Стандартные функции и ключевые слова IEC 61131-3, **отвергаемые `iec2c`** как
/// идентификаторы пользователя. Сравнение — без учёта регистра (см.
/// [`check_st_name`]), поэтому имена даны в нижнем регистре.
///
/// ⚠️ Пополнять **только** проверенным пробой (`var <имя>: u8` → `iec2c`): см.
/// заголовок модуля.
const IEC_RESERVED: &[&str] = &[
    // Строковые функции.
    "left", "right", "mid", "concat", "len", "find", "insert", "delete", "replace",
    // Выбор / ограничение.
    "sel", "limit", "mux", "min", "max", // Числовые.
    "abs", "sqrt", "expt",
    // Сдвиги / вращения над битовыми строками.
    "shl", "shr", "rol", "ror", // Сравнения-функции.
    "gt", "ge", "le", "lt", "eq", "ne",
    // Стандартные функциональные блоки (триггеры, таймеры, счётчики).
    "sr", "rs", "ton", "tof", "tp", "ctu", "ctd", "ctud", "r_trig", "f_trig",
    // Ключевые слова SFC и управления.
    "step", "action", "exit",
    // Стандартные типы (идентификатором пользователя быть не могут).
    "time", "date", "real", "lreal", "int", "sint", "dint", "lint", "usint", "uint", "udint",
    "ulint", "byte", "word", "dword", "lword", "bool", "string", "wstring",
];

/// Строит диагностику `ST-014` — идентификатор занят стандартной библиотекой IEC.
///
/// Текст **называет причину**, которой нет в диагностике `iec2c` (та говорит про
/// `AT %…`, которых в объявлении нет).
fn st014(name: &str, loc: Location) -> Diagnostic {
    Diagnostic::error(
        loc,
        format!(
            "имя '{}' совпадает (без учёта регистра) со стандартной функцией \
             либо ключевым словом IEC 61131-3 и идентификатором в Structured Text \
             быть не может: пространство имён IEC плоское и регистронезависимое. \
             Это НЕ ключевое слово языка Takt — модель остаётся валидной для целей \
             'c', 'c-hal', 'plantuml', 'rust' и 'sv'. Переименуйте элемент в \
             исходнике .takt, если модель нужна на ПЛК",
            name
        ),
    )
    .with_code("ST-014")
}

/// Проверяет, что имя пригодно как идентификатор Structured Text.
///
/// Сравнение — **без учёта регистра**: идентификаторы IEC регистронезависимы,
/// поэтому `left`, `LEFT` и `Left` — одно и то же имя.
///
/// # Ошибки
/// [`ST-014`](st014) — имя занято стандартной библиотекой или ключевым словом IEC.
pub(crate) fn check_st_name(name: &str, loc: Location) -> Result<(), Diagnostic> {
    if IEC_RESERVED.iter().any(|kw| kw.eq_ignore_ascii_case(name)) {
        return Err(st014(name, loc));
    }
    if let Some(ch) = non_ascii_char(name) {
        return Err(st020(name, ch, loc));
    }
    Ok(())
}

/// Первый символ имени вне алфавита идентификатора IEC 61131-3 (или `None`).
///
/// Алфавит — `[A-Za-z0-9_]`; всё прочее `iec2c` отвергает разбором.
fn non_ascii_char(name: &str) -> Option<char> {
    name.chars()
        .find(|c| !(c.is_ascii_alphanumeric() || *c == '_'))
}

/// Строит диагностику `ST-020` — символ вне алфавита идентификатора IEC.
///
/// ⚠️ Отказ принадлежит **цели**, а не языку: `c` и `rust` такие имена
/// переводят, и их гейты вывод принимают (замер 2026-08-04). Прежде отказ
/// приходил от `iec2c` и **на порождённом файле** («unclosed output variable(s)
/// declaration») — сообщение, по которому исходную причину не опознать.
fn st020(name: &str, ch: char, loc: Location) -> Diagnostic {
    Diagnostic::error(
        loc,
        format!(
            "имя '{name}' содержит символ '{ch}', недопустимый в идентификаторе              IEC 61131-3: алфавит цели — латиница, цифры и '_'. Это НЕ              ограничение языка Takt — модель остаётся валидной для целей 'c',              'c-hal', 'rust' и 'plantuml'. Переименуйте элемент, если модель              нужна для ПЛК"
        ),
    )
    .with_code("ST-020")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn loc() -> Location {
        Location::Codegen
    }

    /// Проверенные пробой имена отвергаются (T8).
    #[test]
    fn test_reserved_names_rejected() {
        for name in [
            "abs", "min", "max", "sel", "limit", "step", "left", "concat",
        ] {
            assert!(
                check_st_name(name, loc()).is_err(),
                "'{}' обязано отвергаться (ST-014)",
                name
            );
        }
    }

    /// Регистр не спасает: `left`/`LEFT`/`Left` — одно и то же (T7/A6).
    #[test]
    fn test_case_insensitive() {
        for name in ["left", "LEFT", "Left", "LeFt"] {
            let err = check_st_name(name, loc()).unwrap_err();
            assert_eq!(err.code.as_deref(), Some("ST-014"), "имя '{}'", name);
        }
    }

    /// Имена, которые `iec2c` ПРИНИМАЕТ, проходить обязаны — иначе ложное
    /// срабатывание сломало бы валидную модель (страж против переусердствования
    /// со списком).
    #[test]
    fn test_accepted_names_pass() {
        for name in [
            "remaining",
            "count",
            "busy",
            "mode",
            "command",
            "value",
            "state",
            "delta",
            "x",
        ] {
            assert!(
                check_st_name(name, loc()).is_ok(),
                "'{}' MatIEC принимает — ST-014 срабатывать не должна",
                name
            );
        }
    }
}
