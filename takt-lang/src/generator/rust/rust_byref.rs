//! Что передаётся в функцию ПО ССЫЛКЕ у цели `rust` (фича 0389).
//!
//! # Зачем отдельный носитель
//!
//! Признак спрашивают **два** печатника — сигнатуры (`rust_func`) и аргумента
//! (`rust_expr`). Разъедься они, порождённый код не собрался бы (`E0308`), и
//! компилятор Rust назвал бы это уже на выводе, а не в инструменте. Отдельный
//! модуль делает копию невозможной по построению.

use crate::semantic::bit_vector::{BitVectorLayout, is_bit_vector, layout};
use crate::semantic::type_node::TypeNode;

/// Передаётся ли параметр этого типа ПО ССЫЛКЕ (фича 0389).
///
/// Массив — да: по значению это копия на каждый вызов, тогда как цель `c`
/// передаёт указатель, а `st` — `VAR_IN_OUT`.
///
/// ⚠️ Упакованный бит-вектор (`[bit;N ≤ 64]`) — **скаляр** (правило 0078), и
/// печать типа у него не массивная: передавать его по ссылке значило бы
/// развести форму аргумента и форму параметра.
///
/// ⚠️ Признак ОБЩИЙ у печати аргумента и печати сигнатуры: разъехавшись, они
/// дают `E0308` — то есть вывод, который не собирается.
pub(crate) fn is_array_by_reference(ty: &TypeNode) -> bool {
    matches!(ty, TypeNode::Array(..)) && !is_bit_vector_scalar(ty)
}

/// Упакованный ли это бит-вектор (`[bit;N ≤ 64]` — скаляр, правило 0078).
fn is_bit_vector_scalar(ty: &TypeNode) -> bool {
    matches!(
        is_bit_vector(ty).map(layout),
        Some(BitVectorLayout::Scalar { .. })
    )
}
