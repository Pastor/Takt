//! Имена перечислителей цели `c` (фича 0195, форма К2).
//!
//! # Зачем отдельная функция
//!
//! Имя перечислителя порта строилось **восемью** местами порознь
//! (`c_header`, `c_hal`, `c_model_init` и пять точек печатника выражений) —
//! россыпь `format!("{}_{}", модель, порт)`. Пока формула была одна и та же,
//! это работало случайно; любая правка (в том числе эта) разъехалась бы.
//!
//! # Почему сегмент `PORT_`
//!
//! Порты и состояния в C — перечислители **одной** области видимости, а в языке
//! это разные сущности. `out settled` рядом с `state Settled` давали один и тот
//! же элемент дважды: `redefinition of enumerator` от `cc` при рапорте `taktc`
//! об успехе. Развести их за автора — решение заказчика 2026-08-03: запрещать
//! такую запись нельзя, потому что она **естественна** (светофор с портами
//! `red/yellow/green` и состояниями `Red/Yellow/Green` — пример документа), а
//! прочие цели и симулятор её исполняют верно.
//!
//! ⚠️ Имена портов **видны пользователю**: они стоят в сигнатуре HAL-колбэка.
//! Смена формы — ломающее изменение для порождённого кода, и она сделана
//! осознанно, ценой обновления снапшотов корпуса.

use crate::semantic::minimap::Name;
use crate::semantic::naming::normalize_lowercase_snakecase;

/// Имя перечислителя порта: `<МОДЕЛЬ>_PORT_<ПОРТ>`.
///
/// Сегмент `PORT_` разводит пространство портов с пространством состояний,
/// которое печатается как `<МОДЕЛЬ>_<СОСТОЯНИЕ>`.
pub(in crate::generator::c) fn port_enum_variant(model_name: &Name, port: &str) -> String {
    format!(
        "{}_PORT_{}",
        model_name.unique_uppercase_snakecase(),
        normalize_lowercase_snakecase(port.to_string()).to_uppercase()
    )
}
