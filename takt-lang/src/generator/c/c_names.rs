//! Имена перечислителей цели `c` (фича 0195, форма К2).
//!
//! # Зачем отдельная функция
//!
//! Имя перечислителя порта строилось **восемью** местами порознь
//! (`c_header`, `c_hal`, `c_model_init` и пять точек печатника выражений) —
//! россыпь `format!("{}_{}", модель, порт)`. Пока формула была одна и та же,
//! это работало случайно; любая правка (в том числе эта) разъехалась бы.
//!
//! # Почему сегмент `PORT_`
//!
//! Порты и состояния в C — перечислители **одной** области видимости, а в языке
//! это разные сущности. `out settled` рядом с `state Settled` давали один и тот
//! же элемент дважды: `redefinition of enumerator` от `cc` при рапорте `taktc`
//! об успехе. Развести их за автора — решение заказчика 2026-08-03: запрещать
//! такую запись нельзя, потому что она **естественна** (светофор с портами
//! `red/yellow/green` и состояниями `Red/Yellow/Green` — пример документа), а
//! прочие цели и симулятор её исполняют верно.
//!
//! ⚠️ Имена портов **видны пользователю**: они стоят в сигнатуре HAL-колбэка.
//! Смена формы — ломающее изменение для порождённого кода, и она сделана
//! осознанно, ценой обновления снапшотов корпуса.

use crate::semantic::minimap::Name;
use crate::semantic::naming::normalize_lowercase_snakecase;

/// Имя перечислителя порта: `<МОДЕЛЬ>_PORT_<ПОРТ>`.
///
/// Сегмент `PORT_` разводит пространство портов с пространством состояний,
/// которое печатается как `<МОДЕЛЬ>_<СОСТОЯНИЕ>`.
pub(in crate::generator::c) fn port_enum_variant(
    model_name: &Name,
    port: &str,
    declared: crate::parser::ast::PortDirection,
    side: crate::parser::ast::PortDirection,
) -> String {
    use crate::parser::ast::PortDirection;
    // ⚠️ ДВУНАПРАВЛЕННЫЙ порт попадает в ОБА перечисления (`_In_…` и `_Out_…`),
    // а перечислители в C делят одну область видимости — имя обязано их
    // различать (фича 0421). Замер 2026-08-23: `inout line: u8 at 0x200;`
    // давал `redefinition of enumerator` у `cc` при НУЛЕВОМ коде возврата
    // `taktc`; эталон, `st`, `st-at` и `rust` вход исполняют.
    //
    // ⚠️ Сегмент печатается ТОЛЬКО двунаправленному порту: имена портов видны
    // пользователю (сигнатура HAL-колбэка), и смена формы у однонаправленных
    // была бы ломающей без нужды (урок 0195).
    let suffix = match declared {
        PortDirection::InOut if side == PortDirection::In => "_IN",
        PortDirection::InOut => "_OUT",
        _ => "",
    };
    format!(
        "{}_PORT_{}{}",
        model_name.unique_uppercase_snakecase(),
        normalize_lowercase_snakecase(port.to_string()).to_uppercase(),
        suffix
    )
}

/// Имя константы перечисления: `ENUM_<МОДЕЛЬ>_<ПЕРЕЧИСЛЕНИЕ>_<ВАРИАНТ>`.
///
/// # Зачем сегмент перечисления
///
/// До фичи 0167 имя строилось как `ENUM_<МОДЕЛЬ>_<ВАРИАНТ>`, то есть
/// перечисление в нём **не участвовало**. Два перечисления одной модели с
/// одноимённым вариантом давали два `#define` с одним именем и разными
/// значениями:
///
/// ```c
/// #define ENUM_TWO_ENUMS_STOP 0
/// #define ENUM_TWO_ENUMS_STOP 5
/// ```
///
/// `cc -Wall -Werror` (флаги гейта проекта) такой файл отвергает
/// (`-Wmacro-redefined`), а держалось это лишь тем, что в корпусе одноимённых
/// вариантов нет. Прочие цели квалифицируют имя перечислением давно:
/// `Command_Stop` (`st`), `COMMAND_STOP` (`sv`), `Command::Stop` (`rust`).
///
/// ⚠️ **Модель в имени остаётся**: в C одно пространство имён на программу, и
/// две модели вправе объявить одноимённые перечисления (класс ADR 0193).
///
/// ⚠️ Имя строит **одна** функция, и зовут её оба конца: печать `#define`
/// (`c_decl`) и печать значения (`c_enum`). Разъехавшись, они дадут ссылку на
/// несуществующий макрос — урок ADR 0195.
pub(in crate::generator::c) fn enum_constant(
    model_name: &Name,
    enum_name: &str,
    variant: &str,
) -> String {
    format!(
        "ENUM_{}_{}_{}",
        model_name.unique_uppercase_snakecase(),
        normalize_lowercase_snakecase(enum_name.to_string()).to_uppercase(),
        normalize_lowercase_snakecase(variant.to_string()).to_uppercase()
    )
}
