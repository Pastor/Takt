//! Значение перечислимого типа печатается **именем константы** (фича 0167).
//!
//! # Что было
//!
//! Цель `c` объявляла константы и тут же их не использовала:
//!
//! ```c
//! #define ENUM_EN_COMMAND_GO 1
//! …
//! model->c = 1;              /* а это, оказывается, Go */
//! ```
//!
//! Читатель порождённого C не узнавал, что `1` — это `Go`, не заглянув в
//! `.takt`. Ровно то положение, из которого фича 0066 вывела цель `st`.
//!
//! # Правило
//!
//! Там, где **известен тип** перечислимого операнда (присваивание, начальная
//! инициализация, сравнение с литералом), число заменяется именем константы.
//!
//! ⚠️ **Догадываться нельзя** (правило 4, дословно от 0066): значение, не
//! совпадающее ни с одним вариантом, печатается **числом** — перечислимой
//! переменной можно присвоить произвольное число, и подмена его именем
//! «похожего» варианта была бы тихой ложью.
//!
//! ⚠️ Имя строит `c_names::enum_constant` — **та же** функция, что печатает
//! `#define`. Второй формулы здесь нет и быть не должно (урок ADR 0195).

use crate::semantic::ModelNode;
use crate::semantic::minimap::Name;
use crate::semantic::type_node::TypeNode;
use std::cell::RefCell;
use std::rc::Rc;

/// Имя константы для значения `value` перечислимого типа `ty`.
///
/// `None` — печатать как есть: тип не перечислимый, перечисление не найдено,
/// владелец недоступен либо значение не совпадает ни с одним вариантом.
///
/// `scope` — модель, из которой видно перечисление (владелец переменной либо
/// текущая модель): поиск идёт `search_enum`, то есть по цепочке `upper`.
pub(in crate::generator::c) fn constant_of(
    ty: &TypeNode,
    value: i128,
    scope: &Rc<RefCell<ModelNode>>,
) -> Option<String> {
    let TypeNode::Enum(enum_name) = ty else {
        return None;
    };
    let def = scope.borrow().search_enum(enum_name)?;
    let (variant, _) = def.variants.iter().find(|(_, v)| *v == value)?;
    // Владелец берётся у САМОГО УЗЛА, а не у модели, которую печатаем:
    // перечисление могло быть унаследовано от родителя, и тогда `#define`
    // объявлен с его именем (класс ADR 0193 — ключ строится из `upper`).
    let owner = def.upper.as_ref().and_then(|w| w.upgrade())?;
    Some(crate::generator::c::c_names::enum_constant(
        &Name::from(owner),
        enum_name,
        variant,
    ))
}
