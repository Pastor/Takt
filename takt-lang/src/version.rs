//! Версия языка Takt — единственный источник истины в коде (фича 0085).
//!
//! Прежде версия языка жила **только** в `README.md`; рассинхрон между
//! документацией и фактическим поведением компилятора ничем не ловился. Фича
//! 0078 подняла язык `0.3.0 → 0.4.0`, но README остался на `0.3.0` — и это
//! прошло незамеченным именно потому, что сверять было не с чем.
//!
//! Теперь номер версии живёт здесь, а гейт `scripts/check-language-version.sh`
//! (в `precheck.sh`, а значит и в CI по фиче 0090) сверяет эту константу с
//! канонической строкой `**Версия языка: X.Y.Z**` в `README.md`: расхождение
//! валит предкоммит (прецедент машинных doc-гейтов — ADR 0027 размер модуля,
//! ADR 0077 реестр кодов).
//!
//! ⚠️ **Версия языка накапливается по циклам** (правило 22 свода `docs/RULE.md`):
//! несколько фич, меняющих язык в одном цикле, вносят изменения в **уже
//! поднятую** версию и **не** поднимают её снова. Подъём делает первая закрытая
//! фича цикла и помечает коммит тегом `v<версия>`. Меняя эту константу, синхронно
//! правь каноническую строку `README.md` — иначе гейт покраснеет.
//!
//! Это **не** версия крейта `takt-lang` (`CARGO_PKG_VERSION`): крейт версионируется
//! по SemVer на каждую фичу, версия языка — накапливается. Они намеренно разные.

/// Текущая версия языка Takt (SemVer, `x.y.z`). Единственный источник истины;
/// `README.md` обязан ей соответствовать (гейт `check-language-version.sh`).
pub const LANGUAGE_VERSION: &str = "0.12.0";

/// Печать версий инструмента — подкоманда `taktc version` (фича 0165).
///
/// ⚠️ **Логика здесь, а не в бинарнике** — образец `address-map` (ADR 0027):
/// так проверяется **вывод**, а не факт вызова. Бинарник остаётся диспетчером.
///
/// ⚠️ Версий **две, и они намеренно разные**: версия крейта растёт по SemVer на
/// каждую фичу, версия языка накапливается по циклам (правило 22). Печатать
/// одну значило бы вводить в заблуждение — какая из них имеется в виду,
/// пользователь угадывать не обязан.
///
/// ⚠️ Ни одно число здесь не написано литералом: обе величины читаются из кода,
/// иначе появился бы второй источник истины — ровно тот, против которого эта
/// константа и заведена.
pub fn version_text() -> String {
    format!(
        "taktc {}\nязык Takt {}",
        env!("CARGO_PKG_VERSION"),
        LANGUAGE_VERSION
    )
}

/// Подкоманда `version`: печатает [`version_text`] и возвращает код процесса.
pub fn run_version_subcommand() -> i32 {
    println!("{}", version_text());
    0
}

#[cfg(test)]
mod tests {
    use super::{LANGUAGE_VERSION, version_text};

    /// A3/A4 (фича 0165): вывод подкоманды несёт **обе** версии — и обе взяты из
    /// кода.
    ///
    /// ⚠️ Сверка идёт с **константой**, а не с литералом `"0.10.0"`. Тест с
    /// литералом пришлось бы править при каждом подъёме версии, и он ничего бы
    /// не доказывал: сам стал бы вторым источником истины — ровно тем, против
    /// которого заведена эта константа.
    #[test]
    fn version_text_carries_both_versions_from_code() {
        let text = version_text();
        assert!(
            text.contains(LANGUAGE_VERSION),
            "вывод обязан нести версию языка: {text:?}"
        );
        assert!(
            text.contains(env!("CARGO_PKG_VERSION")),
            "вывод обязан нести версию крейта: {text:?}"
        );
    }

    /// Версии названы **раздельно**: они намеренно разные (правило 22), и
    /// пользователь не обязан угадывать, какая из них имеется в виду.
    #[test]
    fn version_text_names_which_version_is_which() {
        let text = version_text();
        let lines: Vec<&str> = text.lines().collect();
        assert_eq!(lines.len(), 2, "две версии — две строки: {text:?}");
        assert!(
            lines[0].starts_with("taktc "),
            "первая строка — крейт: {text:?}"
        );
        assert!(lines[1].contains("язык Takt"), "вторая — язык: {text:?}");
    }

    /// Константа экспортирована и имеет форму SemVer-тройки `x.y.z` из
    /// десятичных компонент. Форму стережёт этот тест: гейт
    /// `check-language-version.sh` грепает литерал по этому шаблону.
    #[test]
    fn language_version_is_semver_triple() {
        let parts: Vec<&str> = LANGUAGE_VERSION.split('.').collect();
        assert_eq!(
            parts.len(),
            3,
            "версия языка должна быть тройкой x.y.z, получено {LANGUAGE_VERSION:?}"
        );
        for p in parts {
            assert!(
                !p.is_empty() && p.chars().all(|c| c.is_ascii_digit()),
                "компонент версии должен быть непустым числом, получено {p:?} в {LANGUAGE_VERSION:?}"
            );
        }
    }

    /// Реэкспорт из корня крейта: потребители зовут `takt_lang::LANGUAGE_VERSION`.
    #[test]
    fn re_exported_from_crate_root() {
        assert_eq!(crate::LANGUAGE_VERSION, LANGUAGE_VERSION);
    }
}
