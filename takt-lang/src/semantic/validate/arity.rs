//! Число аргументов вызова обязано совпадать с числом параметров — `SE-122`
//! (фича 0313).
//!
//! # Что было
//!
//! Арность не проверял **никто**, и один вход означал разное. Замер 2026-08-20:
//!
//! | Вход | Эталон | Цели |
//! |---|---|---|
//! | `r := two(1);` (локальная `fn two(a, b)`) | `SIM-021` **в такте** | **все восемь переводят**; `c` печатает `Two(model, 1)` — `cc`: «too few arguments» |
//! | `r := min(1);` (встроенная) | `SIM-020` с текстом **о другом** | `c` печатает `model->r = ;`, `st` — `min(1)`, `rust`/`sv` отказывают |
//!
//! Первая строка — «инструмент рапортует об успехе, а вывод невалиден» (класс
//! 0262, 0287): код возврата `taktc` **ноль**, а порождённый C не собирается.
//!
//! # Почему проверка одна на оба вида
//!
//! Правило одно — «вызов обязан отвечать объявлению», — а значит и место одно
//! (урок 0203). Виды функции различаются лишь тем, откуда берётся список
//! параметров: у встроенной он в реестре `semantic::builtin`, у локальной — в
//! разрешённом узле, у неразрешённой — в сыром АСД.
//!
//! ⚠️ **Внешняя функция (`extern`) под правило не подпадает:** её объявление
//! задаёт сигнатуру, и число аргументов проверяется так же — но тело живёт вне
//! программы, поэтому сравнивать не с чем, кроме объявления. Оно и берётся.

use super::*;
use crate::semantic::FunctionDefinitionNode;

/// Проверяет число аргументов вызова; `None` — вызов согласован.
///
/// ⚠️ Неразрешённое определение (`Unresolved`) проверяется **по сырому АСД**:
/// тела функций строятся стадией 5, а судьи `validate` идут после неё — но в
/// ячейке ссылки лежит снимок, снятый при разрешении имени (засада 0204).
pub(super) fn check_call(
    def: &Rc<RefCell<FunctionDefinitionNode>>,
    args: &[ExpressionNode],
) -> Option<Diagnostic> {
    let (name, expected, loc) = match &*def.borrow() {
        FunctionDefinitionNode::Builtin(name, params, _) => {
            ((*name).to_string(), params.len(), Location::Builtin)
        }
        FunctionDefinitionNode::Local { raw, .. } => (
            raw.name.as_ref()?.name.clone(),
            raw.params.len(),
            raw.name.as_ref()?.loc,
        ),
        FunctionDefinitionNode::External { name, params, .. } => {
            (name.clone(), params.len(), Location::Builtin)
        }
        FunctionDefinitionNode::Unresolved(raw) => (
            raw.name.as_ref()?.name.clone(),
            raw.params.len(),
            raw.name.as_ref()?.loc,
        ),
        // Имя не разрешилось ни во что: об этом говорит своя диагностика
        // (`SE-004`) ниже по конвейеру, и второй ответ на тот же вход здесь
        // был бы шумом.
        FunctionDefinitionNode::None => return None,
    };
    if expected == args.len() {
        return None;
    }
    Some(
        Diagnostic::error(
            loc,
            format!(
                "функция '{name}': объявлено параметров {expected}, передано аргументов {}. \
                 Прежде такой вызов принимался молча: цель 'c' печатала код, который \
                 отвергает 'cc', а эталон останавливал прогон уже в такте",
                args.len()
            ),
        )
        .with_code("SE-122"),
    )
}
