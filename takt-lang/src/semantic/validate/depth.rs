//! Ограничение глубины рекурсии семантических обходов (фича 0129).
//!
//! ## Зачем
//!
//! Построение семантического дерева рекурсивно по **структуре текста**:
//! `construct_expression` спускается во вложенные выражения, `resolve_condition`
//! — во вложенные условия, `resolve_ast_statement` — во вложенные операторы.
//! Глубина такой рекурсии задаётся не размером модели, а тем, сколько скобок или
//! `if` написал автор, — и на глубине порядка трёхсот **стек кончается**.
//!
//! Прежде это выглядело как `SIGABRT` с сообщением `has overflowed its stack`
//! **без диагностики**, причём у всех трёх инструментов сразу: `taktc compile`,
//! `taktc verify` и `takt-sim`. Парсер при этом ту же программу переживал
//! (`taktc fmt` отрабатывал штатно) — потолок находился именно в семантике.
//!
//! ## Как устроено
//!
//! Счётчик глубины — потоковый (`thread_local`): библиотеку зовут из LSP, где
//! потоков несколько, и общий счётчик считал бы чужую работу. Вход в рекурсию —
//! [`enter`]; выход учитывается **автоматически** при разрушении [`DepthGuard`],
//! поэтому ранний возврат по `?` не «залипает» на счётчике.
//!
//! ## Почему предел именно 32
//!
//! Замер (фича 0129): в потоке с 2 МиБ стека — столько по умолчанию у потока
//! теста `cargo test` — глубина 48 проходит, 64 роняет процесс; в основном
//! потоке (8 МиБ) порог лежит между 240 и 280. То есть один кадр рекурсии стоит
//! десятки килобайт. Предел 32 оставляет запас **и** в самом стеснённом из
//! поддерживаемых окружений, а для реальных спецификаций недостижим: вложенность
//! скобок или `if` глубже трёх десятков — признак порождённого текста, а не
//! написанного человеком.

use std::cell::Cell;

use crate::diagnostics::{Diagnostic, Location};

/// Предельная глубина вложенности выражений, условий и операторов.
///
/// Обоснование значения — в описании модуля (замер стека, фича 0129).
pub const MAX_NESTING_DEPTH: usize = 32;

thread_local! {
    /// Текущая глубина рекурсии семантического обхода в этом потоке.
    static DEPTH: Cell<usize> = const { Cell::new(0) };
}

/// Отметка о входе в рекурсию: уменьшает счётчик при разрушении.
///
/// Значение возвращается вызывающему намеренно — держать его до конца
/// рекурсивного вызова и есть учёт выхода.
#[derive(Debug)]
#[must_use = "глубина учитывается, пока жива эта отметка"]
pub struct DepthGuard(());

impl Drop for DepthGuard {
    fn drop(&mut self) {
        DEPTH.with(|d| d.set(d.get().saturating_sub(1)));
    }
}

/// Входит на уровень глубже; отдаёт диагностику `SE-062` при превышении предела.
///
/// `loc` — место в исходнике, если оно известно. У операторов позиция есть не у
/// всех узлов АСД, поэтому параметр необязателен: сообщение без координат
/// честнее выдуманных (позиции `Implicit` координат не имеют).
pub fn enter(loc: Option<Location>) -> Result<DepthGuard, Diagnostic> {
    DEPTH.with(|d| {
        let next = d.get() + 1;
        if next > MAX_NESTING_DEPTH {
            return Err(Diagnostic::error(
                loc.unwrap_or(Location::Implicit),
                format!(
                    "превышен предел вложенности ({MAX_NESTING_DEPTH}): \
                     выражение, условие или оператор вложены слишком глубоко"
                ),
            )
            .with_code("SE-062"));
        }
        d.set(next);
        Ok(DepthGuard(()))
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Счётчик обязан возвращаться к нулю: иначе следующая компиляция в том же
    /// потоке (а в LSP их поток переиспользуется) упрётся в чужой остаток.
    #[test]
    fn guard_releases_depth_on_drop() {
        {
            let _a = enter(None).expect("уровень 1");
            let _b = enter(None).expect("уровень 2");
            assert_eq!(DEPTH.with(Cell::get), 2);
        }
        assert_eq!(DEPTH.with(Cell::get), 0);
    }

    /// Предел срабатывает ровно на `MAX_NESTING_DEPTH + 1`, а не «примерно там».
    #[test]
    fn limit_triggers_exactly_after_max_depth() {
        let mut held = Vec::new();
        for level in 1..=MAX_NESTING_DEPTH {
            held.push(enter(None).unwrap_or_else(|_| panic!("уровень {level} обязан пройти")));
        }
        let err = enter(None).expect_err("уровень сверх предела обязан дать диагностику");
        assert_eq!(err.code.as_deref(), Some("SE-062"));
        drop(held);
        assert_eq!(DEPTH.with(Cell::get), 0);
    }

    /// Парный сторож к интеграционным тестам (`tests/deep_nesting_tests.rs`):
    /// там предел продублирован числом, потому что модуль `pub(crate)`. Если
    /// константу изменить, покраснеет этот тест — и станет видно, что вторую
    /// сторону надо править тоже.
    #[test]
    fn constant_matches_documented_limit() {
        assert_eq!(
            MAX_NESTING_DEPTH, 32,
            "предел изменён: обновите tests/deep_nesting_tests.rs и обоснование в шапке модуля"
        );
    }

    /// Ранний возврат по `?` не должен «залипать» на счётчике.
    #[test]
    fn early_return_does_not_leak_depth() {
        fn inner() -> Result<(), Diagnostic> {
            let _g = enter(None)?;
            Err(Diagnostic::error(
                Location::Implicit,
                "ранний выход".to_string(),
            ))
        }
        let _ = inner();
        assert_eq!(DEPTH.with(Cell::get), 0);
    }
}
