//! Внутренний инвариант семантики нарушен: `SE-119` (фича 0276).
//!
//! # Зачем воронка
//!
//! Часть отказов семантики — не ответ автору, а признак **дефекта
//! инструмента**: сюда приходит только то, что более ранняя проверка обязана
//! была отсечь. Замер 2026-08-19 нашёл восемь таких мест
//! (`semantic/function.rs` ×3, `tree.rs` ×2, `named_block.rs`,
//! `condition/mod.rs`, `extend.rs`), и все строили диагностику конверсией
//! `From<&str>`: код печатался `[?]`, а позиция вырождалась в
//! `Location::Source(0, 0, 0)` — то есть «начало первого файла», координата
//! **ложная**, а не отсутствующая.
//!
//! Два места из восьми оказались **достижимы** и получили свои коды
//! (`SE-117`, `SE-118`); остальные — внутренние инварианты, и им нужен не
//! отдельный код на каждый, а **один общий**, называющий вид нарушения словом.
//! Приём тот же, что у цели `c`: `CC-023` — «узел не прошёл понижение»
//! (фича 0212).
//!
//! ⚠️ **Недостижимость держат ДРУГИЕ проверки** (`SE-034`, `SE-004`, `SE-081`
//! и прочие) — она свойство их работы, а не этого модуля. Если такая
//! диагностика когда-нибудь появится в выводе, это сообщение о **дефекте**, и
//! текст обязан помочь найти место, а не притворяться ответом автору.

use crate::diagnostics::Diagnostic;

/// Строит `SE-119` — нарушен внутренний инвариант семантики.
///
/// [`no_diagnostic`] — частый случай: проход завершился неудачей, не оставив
/// диагностики.
///
/// `what` называет вид нарушения **словом**, а не дампом узла (правило фичи
/// 0231): `Debug`-представление в тексте диагностики — отдельный класс, который
/// правился трижды.
pub(crate) fn internal(what: &str) -> Diagnostic {
    Diagnostic::error(
        crate::diagnostics::Location::Codegen,
        format!(
            "внутренний инвариант семантики нарушен: {what}. Это дефект компилятора, а не \
             ошибка модели: до этого места вход обязана была отсечь более ранняя проверка. \
             Сообщите о случае вместе с исходником"
        ),
    )
    .with_code("SE-119")
}

/// `SE-119` для запасного хода «неудача без диагностики».
///
/// Отдельная функция, чтобы место вызова оставалось однострочным: разбор
/// `unwrap_or_else` в три строки раздувал бы `tree.rs`, который и так стоит в
/// реестре узаконенного долга по размеру.
pub(crate) fn no_diagnostic(what: &str) -> Diagnostic {
    internal(&format!(
        "{what} завершилось неудачей, не оставив диагностики"
    ))
}
