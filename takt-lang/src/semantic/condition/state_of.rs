//! Паттерн «текущее состояние модели»: `S(Модель) = Состояние` и его краткая
//! форма `Модель = Состояние`.
//!
//! Обе записи означают одно, и распознавать их обязаны **одинаково** все
//! потребители: канонизация скобок (фича 0074), судья условий
//! (`validate/common.rs`), печатники целей `c` и `rust`. До фичи 0203
//! распознавание было написано **трижды** и разъехалось: цели знали обе формы,
//! а судья — только `S(Модель)`, из-за чего `ref X: E != End;` отвергался
//! `SE-025`, хотя цель `c` ту же запись переводит (`model->…state !=
//! MODEL_STATE`). Расхождение дожило потому, что единственный носитель краткой
//! формы в корпусе (`examples/extend_complex.takt`) стоял в **формуле**, а
//! формулы не обходил никто (тот же дефект 0203).
//!
//! ⚠️ Правая часть паттерна (имя состояния) остаётся **неразрешённой** и здесь
//! не трогается: `End` — состояние модели-аргумента, а не той, где записано
//! условие (инвариант рёбер `ref`, `CLAUDE.md`). Разрешает его тот, кто знает
//! область видимости: судья — проверкой (`SE-033`), генератор — печатью имени.

use crate::semantic::{ConditionNode, FunctionDefinitionNode, ModelNode};
use std::cell::RefCell;
use std::rc::Rc;

/// Модель, о состоянии которой говорит условие: `S(Модель)` либо краткое
/// `Модель`. `None` — это не паттерн «текущее состояние модели».
///
/// Единый источник истины о форме паттерна: зовут судья условий, печатники
/// целей `c`/`rust` и канонизация скобок ([`is_state_of`]).
pub(crate) fn state_of_model(cond: &ConditionNode) -> Option<&Rc<RefCell<ModelNode>>> {
    match cond {
        ConditionNode::Model(model, _) => Some(model),
        ConditionNode::Function(fun, args, _) => {
            if !matches!(&*fun.borrow(), FunctionDefinitionNode::Builtin("S", ..)) {
                return None;
            }
            // Арность встроенной `S` — ровно один параметр (`model`), проверена
            // семантикой; аргумент обязан быть моделью.
            match args.first().map(|a| a.as_ref())? {
                ConditionNode::Model(model, _) => Some(model),
                _ => None,
            }
        }
        _ => None,
    }
}

/// Является ли условие паттерном «текущее состояние модели».
///
/// Булев вид [`state_of_model`] — второго разбора формы здесь нет: разъехавшись,
/// они дали бы разный ответ на один текст.
pub(crate) fn is_state_of(cond: &ConditionNode) -> bool {
    state_of_model(cond).is_some()
}
