//! Отказы на **инициализаторе объявления**: почему запись, которую компилятор
//! вычислить не может, не доезжает до потребителей.
//!
//! Правил здесь четыре, и все они об одном месте — выражении, которое считается
//! **до первого такта**:
//!
//! | Код | Что запрещено | Фича |
//! |---|---|---|
//! | `SE-109` | ссылка **вперёд** на объявление ниже по тексту | 0246 |
//! | `SE-114` | дробная арифметика, требующая **округления** | 0300 |
//! | `SE-084` | вызов **внешней** функции | 0305 |
//! | `SE-084` | вызов функции, которую вычислитель исполнить не смог | 0306 |
//!
//! ⚠️ Модуль выделен из `declaration.rs` по **границе ответственности**, а не
//! ради строк: свёртка решает, чем стало значение, а эти судьи — законна ли
//! сама запись. Тексты диагностик живут рядом с признаками, которые их
//! порождают.

use super::{collect_identifiers, declaration_position, is_literal};
use crate::diagnostics::{Diagnostic, Location};
use crate::semantic::{ModelNode, VariableNode};
use std::cell::RefCell;
use std::collections::BTreeMap;
use std::rc::Rc;

/// Несвёрнутая дробная АРИФМЕТИКА в инициализаторе — `SE-114` (фича 0300).
///
/// # Почему именно дробное и почему ошибка
///
/// Замер ADR 0300: `var d: float := 1.0 / 3.0;` даёт `0.0` у эталона и
/// `model->d = 1.0 / 3.0;` (то есть `0.333…`) у цели `c` — молча. Общего
/// поведения у такой записи не существует: эталон вычисляет дробное **своими**
/// правилами округления, а свернуть их при компиляции значит завести второй
/// источник истины (довод фичи 0185, он же в `const_eval`).
///
/// Точная арифметика (`+`, `-`, `*` над десятичными литералами, в том числе
/// смешанная с целым) сюда не доходит — её свернул `const_eval::decimal`.
/// Остаётся то, что требует **округления**: прежде всего деление.
///
/// ⚠️ **Отказ узкий, и это замер, а не осторожность.** Отвергается только
/// **арифметика**: формы, которые эталон вычислять умеет, обязаны остаться
/// законными. Приведение `as` — ровно такая форма (фича 0205 научила ей второй
/// вычислитель), и первая, слишком широкая редакция проверки отвергла
/// `var v := 3 as q(4, 4);` — вход, на котором эталон и цель **уже согласны**
/// (48 у обоих). Поймали это сторожа 0205, а не чтение.
///
/// ⚠️ Целых это не касается: их свёртка (0192) точна всегда, а невычислимое
/// целое остаётся законным — сужать язык там повода нет.
///
/// ⚠️ **Граница:** невычислимая НЕарифметическая форма (вызов функции в
/// дробном инициализаторе) остаётся с прежним поведением — она вне объёма
/// фичи и вынесена кандидатом.
/// Инициализатор, зовущий **внешнюю** функцию, — ошибка `SE-084` (фича 0305).
///
/// # Почему запрет, а не молчание
///
/// Значение `extern`-функции при компиляции неизвестно **по определению**: её
/// тело живёт вне программы. Замер 2026-08-20 на входе
/// `var mirror: u8 := sensor();` дал **три** разных ответа:
///
/// | Потребитель | Ответ |
/// |---|---|
/// | эталон | `mirror = 0` — молча |
/// | `c`, `c-hal` | `CC-023` |
/// | `rust` | `RS-011` |
/// | `sv`, `sv-mmio` | `SV-002` |
/// | **`st`, `st-at`** | **код 0 и потерянный инициализатор** (`mirror : USINT;`) |
///
/// Худший ответ — молчаливая потеря: прошивка получает необъявленное начальное
/// значение, и никто об этом не говорит. Отказ приводит девять потребителей к
/// одному ответу, и он же указывает автору штатный путь — присвоить в теле.
///
/// ⚠️ Запрет **узкий**: только вызов внешней функции. Вызов локальной
/// вычисляется (`const_eval::call`), и `var x := seed();` работает — проверено
/// контрольным входом. Прочие невычислимые формы остаются как есть: решение
/// заказчика (Option D фичи 0192) расширяет язык, а не ужесточает.
pub(super) fn initializer_calls_extern(
    source: &crate::parser::ast::Expression,
    model: &Rc<RefCell<ModelNode>>,
) -> Option<String> {
    use crate::parser::ast::Expression as E;
    // ⚠️ Форм внешней функции в узле ДВЕ, и на этой стадии встречается ВТОРАЯ:
    // тела функций разрешаются стадией 5, а свёртка идёт стадией 2, поэтому в
    // ячейке лежит `Unresolved(FunctionDefine { external: true, … })`. Пока
    // проверялась только форма `External`, ветвь была фактически мёртвой —
    // отказ выдавал обход `validate` (тот же код, свой текст), и находка эта
    // принадлежит фиче 0306: до неё разницы не было видно, потому что оба
    // пути молчали об одном и том же входе одинаково.
    if let E::Function(_, id, _) = source
        && let Some(def) = model.borrow().search_func(&id.name)
        && match &*def.borrow() {
            crate::semantic::FunctionDefinitionNode::External { .. } => true,
            crate::semantic::FunctionDefinitionNode::Unresolved(raw) => raw.external,
            _ => false,
        }
    {
        return Some(id.name.clone());
    }
    let (left, right) = source.components();
    left.and_then(|e| initializer_calls_extern(e, model))
        .or_else(|| right.and_then(|e| initializer_calls_extern(e, model)))
}

/// Есть ли в инициализаторе вызов функции (любой, включая вложенный).
///
/// Признак **синтаксический**: спрашивается форма записи, а не разрешённое
/// имя. Так и надо — отказ выдаётся ровно тогда, когда автор **написал**
/// вызов, а вычислитель на нём споткнулся; имя, которое никуда не разрешилось,
/// судит своя диагностика (`SE-004`) ниже по конвейеру.
/// ⚠️ Области видимости признак не спрашивает **намеренно**: имя, которое никуда
/// не разрешилось, — не предмет этого правила, и передавать сюда модель значило
/// бы обещать разбор, которого нет.
pub(super) fn initializer_calls_function(source: &crate::parser::ast::Expression) -> bool {
    use crate::parser::ast::Expression as E;
    if matches!(source, E::Function(_, _, _)) {
        return true;
    }
    let (left, right) = source.components();
    left.is_some_and(initializer_calls_function) || right.is_some_and(initializer_calls_function)
}

/// Инициализатор зовёт функцию, которую компилятор исполнить не смог, —
/// `SE-084` с **причиной** вычислителя (фича 0306).
///
/// # Почему отказ, а не молчание
///
/// Замер 2026-08-20 на входе, где тело функции читает переменную модели
/// (`fn wobble() -> u8 { var t := base; t := t + 1; return t; }`,
/// `var scale: u8 := wobble();`), дал **четыре** разных ответа:
///
/// | Потребитель | Ответ |
/// |---|---|
/// | эталон | `scale = 0` — **молча**, при нулевом коде возврата |
/// | `st`, `st-at` | код 0 и **потерянный** инициализатор (`scale : USINT;`) |
/// | `c`, `c-hal` | `CC-023` — код «узел не прошёл понижение», то есть дефект инструмента |
/// | `rust` | `RS-011`; `sv`, `sv-mmio` — `SV-002`; `plantuml` — принимает |
///
/// Причину при этом **уже знал сам вычислитель** (`const_eval::call` называет
/// её словами — чтение переменной, порт, `extern`, неподдержанный оператор,
/// исчерпанный бюджет), но свёртка выбрасывала его диагностику вместе с
/// ошибкой. Отказ приводит девять потребителей к одному ответу и цитирует
/// причину — образец взят у начального значения порта (0187), где так делается
/// с самого начала.
///
/// ⚠️ Отказ **узкий**: спрашивается наличие вызова. Вычислимый вызов
/// сворачивается в литерал и остаётся законным (`var x := seed();` — контроль
/// замера, все девять дают `3`), прочие невычислимые формы не затронуты
/// (решение заказчика Option D фичи 0192 расширяет язык, а не ужесточает).
pub(super) fn unfoldable_call(name: &str, cause: &Diagnostic, loc: Location) -> Diagnostic {
    // ⚠️ Цитируется ПРИЧИНА, а не всё сообщение: общая вводная вычислителя
    // («выражение не вычисляется при компиляции») здесь уже сказана своими
    // словами, и оставленная целиком она читалась бы как заикание. Вводная
    // вида «функция 'f' не вычисляется…» снимается тоже — имя функции в ней
    // полезно, но повторяет то, что автор видит в самой записи.
    let reason = cause
        .message
        .split_once("не вычисляется при компиляции: ")
        .map_or(cause.message.as_str(), |(_, tail)| tail);
    Diagnostic::error(
        loc,
        format!(
            "инициализатор '{name}' зовёт функцию, которую компилятор вычислить не может: \
             {reason}. Начальное значение выставляется до первого такта, и прежде \
             потребители расходились молча: эталон оставлял ноль, а цель 'st' теряла \
             инициализатор без единого слова. Присвойте в теле состояния — \
             'always {{ {name} := …; }}'"
        ),
    )
    .with_code("SE-084")
}

pub(super) fn unfoldable_fractional(
    source: &crate::parser::ast::Expression,
    name: &str,
    ty: Option<&crate::semantic::type_node::TypeNode>,
    loc: Location,
) -> Option<Diagnostic> {
    use crate::semantic::type_node::TypeNode;
    if is_literal(source) {
        return None;
    }
    if !matches!(ty, Some(TypeNode::Rational | TypeNode::Fixed { .. })) {
        return None;
    }
    if !contains_arithmetic(source) {
        return None;
    }
    Some(
        Diagnostic::error(
            loc,
            format!(
                "инициализатор '{name}' — дробное выражение, которое компилятор не может \
                 вычислить точно: округление дробных задано эталоном симулятора, и \
                 посчитав здесь, компилятор дал бы значение, которого симулятор не \
                 вычислит (прогон показал бы ноль, а прошивка — своё число, и молча). \
                 Задайте готовый литерал — например 'var {name}: … := 0.333;' — либо \
                 вычисляйте в теле состояния: 'always {{ {name} := …; }}'"
            ),
        )
        .with_code("SE-114"),
    )
}

/// Есть ли в выражении бинарная арифметика.
///
/// Обход идёт общим разбором [`ast::Expression::components`], поэтому новый узел
/// АСД сам собой попадает под спуск, а список арифметических форм остаётся
/// коротким и явным.
fn contains_arithmetic(expr: &crate::parser::ast::Expression) -> bool {
    use crate::parser::ast::Expression as E;
    if matches!(
        expr,
        E::Power(..)
            | E::Multiply(..)
            | E::Divide(..)
            | E::Modulo(..)
            | E::Add(..)
            | E::Subtract(..)
    ) {
        return true;
    }
    let (left, right) = expr.components();
    left.is_some_and(contains_arithmetic) || right.is_some_and(contains_arithmetic)
}

/// Ссылка вперёд: имя переменной, объявленной НИЖЕ по тексту (фича 0246).
///
/// Возвращает диагностику `SE-109`, если инициализатор `source` упоминает
/// переменную (`var`) той же карты объявлений, чьё объявление стоит после
/// объявления `owner`.
///
/// # Что проверяется точно, а что оставлено законным
///
/// Правило 0192 — «имя в инициализаторе значит начальное значение и ссылается
/// только НАЗАД по тексту» — до этой фичи не проверялось ничем.
///
/// ⚠️ **Константы исключены намеренно:** у них ссылка вперёд разрешается
/// проходами до неподвижной точки (фича 0204) и даёт согласованный результат у
/// эталона и целей — проверено пробой. Запрет сломал бы работающие входы.
///
/// ⚠️ **Прочие невычислимые формы (порт, вызов функции, обращение к полю)
/// остаются законными:** фича не ужесточает язык, а исполняет уже принятое
/// правило. Отвергать всё невычислимое значило бы ломать входы, которых нет в
/// корпусе, — тот же довод, по которому 0192 выбрала расширение, а не запрет.
pub(super) fn forward_reference(
    source: &crate::parser::ast::Expression,
    owner: &str,
    variables: &BTreeMap<String, VariableNode>,
) -> Option<Diagnostic> {
    let after = declaration_position(&variables[owner]);
    let mut names = Vec::new();
    collect_identifiers(source, &mut names);
    for (name, loc) in names {
        let Some(other) = variables.get(&name) else {
            continue;
        };
        // Только переменные: константа вперёд законна (см. заголовок функции).
        if !matches!(other, VariableNode::Simple { .. }) {
            continue;
        }
        if declaration_position(other) <= after {
            continue;
        }
        return Some(
            Diagnostic::error(
                loc,
                format!(
                    "переменная '{name}' объявлена ниже: в инициализаторе имя значит \
                     НАЧАЛЬНОЕ значение и ссылается только назад по тексту. \
                     Переставьте объявления либо возьмите константу"
                ),
            )
            .with_code("SE-109"),
        );
    }
    None
}
