//! Целочисленные операции константного вычисления — **одна** таблица (фича 0208).
//!
//! # Зачем модуль
//!
//! Правила были написаны **дважды**: `const_eval::int_op` (общий вычислитель,
//! носитель `i128`) и `address_map::eval::apply_binary` (выражение адреса,
//! носитель `i64`). Обе таблицы перечисляли те же операции, ту же обёртку при
//! переполнении, тот же отказ на делении на ноль и ту же границу сдвига
//! `0..63` — и уже разошлись формулировками («сдвиг **допустим** только на
//! 0..63 бит» против «сдвиг **определён** только на 0..63 бит»).
//!
//! Урок 0042 записан в живом контексте прямо: арифметика адреса живёт в одном
//! месте, потому что «разъехавшись, они дали бы **разный адрес для одного
//! текста**». Тот же довод действует на уровень выше: две таблицы правил для
//! одного языка расходятся молча, и разойдутся они не в тексте сообщения, а в
//! значении.
//!
//! # Что здесь есть и чего здесь нет
//!
//! Здесь — **только** таблица операций над целыми: результат либо число, либо
//! булево. Здесь **нет** диагностик: их текст и код принадлежат вызывающему
//! (у адреса — `SE-055` со своей формулировкой, у общего вычислителя —
//! `SE-083`), и сводить их к одному значило бы менять наблюдаемое поведение
//! ради внутренней опрятности.
//!
//! Здесь **нет** и носителя: вычисление идёт в `i128`, а сужение к своему типу
//! делает вызывающий. Для адреса это `as i64` — то же самое, что прежняя
//! обёртка `wrapping_*` по 64 битам (`i64::MAX + 1` в `i128` даёт `2⁶³`, а
//! `as i64` — `i64::MIN`).
//!
//! ⚠️ **Третьего дубля нет.** Вычислитель константной выдержки
//! (`semantic/condition/after_const.rs`, фича 0143) считает **наносекунды**
//! `checked_add`/`checked_sub` и отвечает `Cause::Overflow` — у него другая
//! семантика (проверяемая, а не обёртка) и другой домен (длительность).
//! Загонять его сюда значило бы навязать длительности обёртку целого.

/// Результат операции: целое либо булево (сравнения и логика).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum IntOutcome {
    /// Числовой результат.
    Int(i128),
    /// Результат сравнения или логической операции.
    Bool(bool),
}

/// Почему операция не выполнена. Текст и код диагностики — за вызывающим.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum IntOpError {
    /// Деление на ноль.
    DivisionByZero,
    /// Остаток от деления на ноль.
    RemainderByZero,
    /// Сдвиг на отрицательное число либо на 64 бита и более.
    ///
    /// ⚠️ В Rust такой сдвиг — **паника**, поэтому граница проверяется, а не
    /// обрезается: у автора это всегда опечатка.
    ShiftOutOfRange,
    /// Операции с таким знаком в константном вычислении нет.
    UnsupportedOperator,
}

/// Применяет бинарную операцию к целым операндам.
///
/// Переполнение — **обёртка** (`wrapping_*`): норма ADR 0127 для беззнаковых
/// величин, и она же прежде действовала в обеих сведённых сюда таблицах.
/// Сужение результата к своему носителю — задача вызывающего.
pub(crate) fn int_binary(op: &str, a: i128, b: i128) -> Result<IntOutcome, IntOpError> {
    use IntOutcome as O;
    let value = match op {
        "+" => O::Int(a.wrapping_add(b)),
        "-" => O::Int(a.wrapping_sub(b)),
        "*" => O::Int(a.wrapping_mul(b)),
        "/" => {
            if b == 0 {
                return Err(IntOpError::DivisionByZero);
            }
            O::Int(a.wrapping_div(b))
        }
        "%" => {
            if b == 0 {
                return Err(IntOpError::RemainderByZero);
            }
            O::Int(a.wrapping_rem(b))
        }
        "<<" | ">>" => {
            if !(0..64).contains(&b) {
                return Err(IntOpError::ShiftOutOfRange);
            }
            if op == "<<" {
                O::Int(a << b)
            } else {
                O::Int(a >> b)
            }
        }
        "&" => O::Int(a & b),
        "|" => O::Int(a | b),
        "^" => O::Int(a ^ b),
        "=" => O::Bool(a == b),
        "!=" => O::Bool(a != b),
        "<" => O::Bool(a < b),
        "<=" => O::Bool(a <= b),
        ">" => O::Bool(a > b),
        ">=" => O::Bool(a >= b),
        "&&" => O::Bool(a != 0 && b != 0),
        "||" => O::Bool(a != 0 || b != 0),
        _ => return Err(IntOpError::UnsupportedOperator),
    };
    Ok(value)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Обёртка при переполнении — та же норма, что у арифметики языка (0127).
    #[test]
    fn overflow_wraps() {
        assert_eq!(
            int_binary("+", i128::MAX, 1),
            Ok(IntOutcome::Int(i128::MIN))
        );
    }

    /// Сужение к `i64` после вычисления в `i128` даёт ту же обёртку, что
    /// `wrapping_add` по 64 битам, — на этом стоит замена в выражении адреса.
    #[test]
    fn narrowing_to_i64_matches_64bit_wrapping() {
        let Ok(IntOutcome::Int(wide)) = int_binary("+", i128::from(i64::MAX), 1) else {
            panic!("сложение обязано дать число");
        };
        assert_eq!(wide as i64, i64::MAX.wrapping_add(1));
    }

    /// Деление и остаток на ноль — отказ, а не паника.
    #[test]
    fn division_by_zero_is_refused() {
        assert_eq!(int_binary("/", 1, 0), Err(IntOpError::DivisionByZero));
        assert_eq!(int_binary("%", 1, 0), Err(IntOpError::RemainderByZero));
    }

    /// Граница сдвига проверяется с обеих сторон.
    #[test]
    fn shift_range_is_checked() {
        assert_eq!(int_binary("<<", 1, -1), Err(IntOpError::ShiftOutOfRange));
        assert_eq!(int_binary("<<", 1, 64), Err(IntOpError::ShiftOutOfRange));
        assert_eq!(int_binary("<<", 1, 63), Ok(IntOutcome::Int(1i128 << 63)));
    }

    /// Сравнение даёт булево — по этому признаку выражение адреса отличает
    /// операции, которых у него нет.
    #[test]
    fn comparison_yields_bool() {
        assert_eq!(int_binary("<", 1, 2), Ok(IntOutcome::Bool(true)));
    }

    /// Неизвестный знак — отказ, а не молчаливый ноль.
    #[test]
    fn unknown_operator_is_refused() {
        assert_eq!(int_binary("**", 2, 3), Err(IntOpError::UnsupportedOperator));
    }
}
