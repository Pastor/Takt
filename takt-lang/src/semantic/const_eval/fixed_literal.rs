//! Приведение **литерала** к `q(m, n)` — общий носитель (фичи 0383, 0384).
//!
//! # Что было
//!
//! Значение `2.5 as q(8, 8)` известно при компиляции: его считает
//! `const_eval::fixed_repr` (0317). Но зовётся тот только из свёртки
//! **инициализаторов**, и в теле приведение доезжало до целей как написано.
//! Замер 2026-08-22:
//!
//! | Потребитель | `gain := 2.5 as q(8, 8);` |
//! |---|---|
//! | эталон | исполняет |
//! | `c`, `c-hal` | `(int16_t)floor((2.5) * 256.0)` — вызов libm **в рантайме ради константы** |
//! | `st`, `st-at` | `ST-011` «тип источника не выводится статически» |
//! | `rust` | `RS-011` «нужен floor, которого нет в no_std без libm» |
//! | `sv`, `sv-mmio` | `SV-002` «вещественный литерал» |
//!
//! Тексты отказов сами называли пробел: `RS-011` обещал, что литеральный float
//! понижается при компиляции, а `ST-011` — что тип источника неизвестен, хотя
//! источник есть литерал.
//!
//! # Почему печатают ЦЕЛИ, а не сворачивает семантика
//!
//! Подмена узла на целое-представление прямо в дереве (напрашивающееся
//! решение) **ломает законный вход**: проверки идут ПОСЛЕ понижения
//! (`construct_stages` → `validate_model_all`), и `q * Number` ловит `SE-059`
//! «неявное смешение `q(8, 8)` и `[bit;16]`» — то есть запись
//! `gain * (2.0 as q(8, 8))`, которой автор смешение **снимает**, стала бы
//! незаконной. Проверено прогоном (ADR 0383, Option A).
//!
//! Поэтому дерево не трогается, а цели спрашивают этот носитель. Счёт — у
//! `fixed_repr` (0317): второго знания о масштабе 2ⁿ, floor к −∞ и переносе
//! по `W = m + n` не заводится.

use super::fixed_repr;
use crate::semantic::ExpressionNode;
use crate::semantic::type_node::TypeNode;
use crate::semantic::variable::VariableNode;

/// Представление приведения `литерал as q(m, n)`, если источник — литерал.
///
/// `None` — «источник не литерал»: пусть отвечает прежняя ветвь цели (печать
/// масштабирования у `c`, отказ у прочих). Ошибаться этот признак может только
/// в сторону прежнего поведения.
///
/// ⚠️ Имя константы литералом **не** считается: значение там тоже известно, но
/// вопрос принадлежит константному вычислителю, а не печатнику (граница
/// названа в ADR 0383 и вынесена кандидатом).
pub(crate) fn cast_repr(inner: &ExpressionNode, target: &TypeNode) -> Option<i64> {
    let TypeNode::Fixed { m, n, sat } = target else {
        return None;
    };
    let raw = literal_repr(inner, *n)?;
    Some(fixed_repr::normalize(raw, *m, *n, *sat))
}

/// «Сырое» представление литерала — до нормализации по `W`.
fn literal_repr(expr: &ExpressionNode, n: u8) -> Option<i128> {
    match expr {
        // Скобки прозрачны: `(2.5) as q(8, 8)` — тот же литерал.
        ExpressionNode::Parenthesis(inner) => literal_repr(inner, n),
        ExpressionNode::Negate(inner) => literal_repr(inner, n).map(|v| -v),
        ExpressionNode::Number(v) => Some(fixed_repr::from_int(*v, n)),
        ExpressionNode::Rational(text, negative) => {
            fixed_repr::from_decimal_text(text, *negative, n)
        }
        // Имя КОНСТАНТЫ — тот же случай (фича 0384): её инициализатор свёрнут в
        // литерал ещё на стадии 2 (правило 0192), и в ячейке ссылки лежит
        // именно он. Спрашивать вычислитель заново не нужно — и нечем:
        // печатник модели не видит.
        //
        // ⚠️ Изменяемая переменная сюда НЕ подпадает: её значение известно
        // только в такте.
        ExpressionNode::Variable(cell) => match &*cell.borrow() {
            VariableNode::Const { expr, .. } => literal_repr(expr, n),
            _ => None,
        },
        _ => None,
    }
}
