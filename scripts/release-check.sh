#!/bin/sh
# Решение о релизе по подъёму МИНОРНОЙ версии языка (фича 0302).
#
# # Зачем отдельный скрипт, а не логика в workflow
#
# Принцип 0090: логики в `.github/workflows/ci.yml` НЕТ — он ставит инструменты
# и делает один вызов. Причина та же и здесь, только острее: workflow в этом
# проекте **не исполняется** (аккаунт заблокирован по биллингу, замер
# 2026-08-19), поэтому решение обязано быть проверяемым ЛОКАЛЬНО. Скрипт —
# то, что можно прогнать и покрыть сторожем; YAML остаётся тонкой обёрткой.
#
# # Что решает
#
# Сравнивает МИНОРНУЮ часть `takt_lang::LANGUAGE_VERSION` в двух ревизиях.
# Печатает одну строку решения на stdout:
#
#   release <версия>   минорная поднялась — нужен тег `v<версия>` и релиз
#   skip <причина>     релиз не нужен
#
# Код возврата 0 в обоих случаях: «релиза не требуется» — это НЕ ошибка.
# Ненулевой код означает, что решение принять не удалось (нет файла версии,
# нет ревизии) — и тогда молча пропускать релиз нельзя.
#
# ⚠️ ГРАНИЦА: скрипт не ставит тег и не выпускает релиз. Он только отвечает
# «надо ли». Действие выполняет вызывающий — так решение остаётся проверяемым
# без прав на запись в репозиторий.
#
# Использование:
#   scripts/release-check.sh [НОВАЯ_РЕВИЗИЯ [ПРЕДЫДУЩАЯ_РЕВИЗИЯ]]
# По умолчанию: HEAD и HEAD~1.
set -eu

# ⚠️ Скрипт работает в ТЕКУЩЕМ репозитории, а не в своём: `cd` к каталогу
# скрипта здесь был бы дефектом. Он вызывается из чекаута (в CI — из рабочей
# копии job), и первая редакция, уходившая в собственный корень, отвечала про
# ЧУЖУЮ историю — сторож поймал это первым же прогоном.
REL_VERSION_RS="takt-lang/src/version.rs"
VER_RE='[0-9]+\.[0-9]+\.[0-9]+'
NEW_REV="${1:-HEAD}"
OLD_REV="${2:-${NEW_REV}~1}"

# Версия языка в ревизии; пустая строка, если файла в ней нет.
version_at() {
    git show "$1:$REL_VERSION_RS" 2>/dev/null \
        | grep -oE "LANGUAGE_VERSION: &str = \"$VER_RE\"" \
        | grep -oE "$VER_RE" | head -n1
}

minor_of() { printf '%s' "$1" | cut -d. -f1,2; }

NEW_VER="$(version_at "$NEW_REV" || true)"
if [ -z "${NEW_VER:-}" ]; then
    echo "release-check: не удалось прочитать версию языка в '$NEW_REV'" >&2
    exit 1
fi

OLD_VER="$(version_at "$OLD_REV" || true)"
if [ -z "${OLD_VER:-}" ]; then
    # Первый коммит либо мелкий клон: сравнивать не с чем. Молча релизить
    # нельзя — это выпустило бы релиз на ровном месте при каждом shallow-клоне.
    echo "skip нет предыдущей ревизии ($OLD_REV) — сравнивать не с чем"
    exit 0
fi

if [ "$(minor_of "$NEW_VER")" = "$(minor_of "$OLD_VER")" ]; then
    echo "skip минорная версия языка не менялась ($OLD_VER → $NEW_VER)"
    exit 0
fi

# ⚠️ Понижение версии релизом не считается: правило 22 знает только подъём, а
# откат — это исправление истории, и выпускать под него релиз значит закрепить
# ошибку тегом.
NEWEST="$(printf '%s\n%s\n' "$OLD_VER" "$NEW_VER" | sort -V | tail -n1)"
if [ "$NEWEST" != "$NEW_VER" ]; then
    echo "skip минорная версия понижена ($OLD_VER → $NEW_VER) — релиз не выпускается"
    exit 0
fi

# Тег уже стоит — значит подъём помечен вручную (правило 22 этого и требует).
# Повтор не нужен и не является ошибкой: скрипт идемпотентен.
if git rev-parse -q --verify "refs/tags/v$NEW_VER" >/dev/null 2>&1; then
    echo "skip тег v$NEW_VER уже существует — релиз уже помечен"
    exit 0
fi

echo "release $NEW_VER"
