#!/bin/sh
# Гейт сборки расширения Zed (фича 0414).
#
# Правило: конфигурация репозитория обязана оставлять расширение
# `extensions/zed-takt` собираемым РЕДАКТОРОМ. Zed собирает его сам, поэтому
# проверяются два условия, каждое из которых было нарушено замером 2026-08-23:
#
#   Z1 — пин толчейна перечисляет wasm-таргеты. `rust-toolchain.toml` лежит в
#        корне, а rustup ищет его ВВЕРХ ПО ДЕРЕВУ — значит пин действует и на
#        каталог расширения. Zed собирает под `wasm32-wasip2` (версия 1.16.1;
#        более ранние — под `wasm32-wasip1`), и без таргета сборка падает
#        `E0463: can't find crate for core`. Пользователь видит лишь
#        «failed to compile Rust extension»: лог Zed обрезает вывод cargo на
#        первой строке.
#
#   Z2 — у расширения свой каталог сборки. Корневой `.cargo/config.toml`
#        (фича 0251) уводит `target-dir` в `target/precheck`, а Zed ищет
#        артефакт по ФИКСИРОВАННОМУ пути `target/<таргет>/release/<crate>.wasm`
#        внутри каталога расширения. Собранный wasm уезжал туда, где чужой
#        инструмент его не ищет.
#
# ⚠️ ГРАНИЦА: гейт проверяет КОНФИГУРАЦИЮ, а не факт сборки. Прогон `cargo
# build --target wasm32-wasip2` стоил бы предкоммиту загрузки таргета и минут
# компиляции ради кода, который в `precheck.sh` не участвует; вердикт о самой
# сборке даёт редактор. Класс, который гейт ловит, — молчаливое отступление
# конфигурации, а оно и было причиной обоих отказов.
#
# ⚠️ Список таргетов НЕ повторяется в README: два списка одного набора
# расходятся (класс 0084/0193/0195).
#
# Корень переопределяется переменной `ZE_ROOT` (фича 0315) — для сторожа гейта.
#
# POSIX sh, без внешних зависимостей.
set -eu

ROOT="${ZE_ROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
PIN="$ROOT/rust-toolchain.toml"
EXT="$ROOT/extensions/zed-takt"
EXT_CARGO="$EXT/.cargo/config.toml"

FAILED=0
say() { echo "  $1"; }
bad() { echo "  ОШИБКА: $1" >&2; FAILED=1; }

# Расширения нет — проверять нечего (сторож гоняет гейт на урезанных деревьях).
if [ ! -d "$EXT" ]; then
    echo "Расширение Zed: каталог $EXT отсутствует — проверка пропущена."
    exit 0
fi

echo "Гейт сборки расширения Zed (фича 0414)..."

# --- Z1: пин толчейна перечисляет wasm-таргеты -------------------------------
if [ ! -f "$PIN" ]; then
    bad "Z1: не найден пин толчейна $PIN"
else
    for target in wasm32-wasip1 wasm32-wasip2; do
        if grep -q "\"$target\"" "$PIN"; then
            say "Z1: $target перечислен в пине толчейна"
        else
            bad "Z1: $target не перечислен в $PIN — Zed не соберёт расширение
       (rustup читает этот файл и для extensions/zed-takt; отказ приходит
        как «failed to compile Rust extension» без вывода cargo)"
        fi
    done
fi

# --- Z2: у расширения свой каталог сборки ------------------------------------
if [ ! -f "$EXT_CARGO" ]; then
    bad "Z2: не найден $EXT_CARGO — корневой .cargo/config.toml (фича 0251)
       уведёт wasm в target/precheck, а Zed ищет его в каталоге расширения"
elif grep -q '^[[:space:]]*target-dir[[:space:]]*=[[:space:]]*"target"' "$EXT_CARGO"; then
    say "Z2: расширение собирается в свой target/"
else
    bad "Z2: $EXT_CARGO не задаёт target-dir = \"target\""
fi

if [ "$FAILED" -ne 0 ]; then
    echo "Гейт расширения Zed: есть нарушения." >&2
    exit 1
fi
echo "Расширение Zed: конфигурация сборки на месте."
