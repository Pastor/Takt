// Это не текст оболочки, а **документ автора**: с первого нажатия клавиши он
// становится его исходником, уезжает в черновик и в ссылку-снимок. Переведи
// его — и два читателя, поделившись ссылками, обменялись бы разными моделями,
// а комментарии в коде разошлись бы с тем, что показывает документ `book/`.
//
// Отдельный файл потому, что гейт веб-части требует, чтобы русского текста вне
// словаря на странице не было (задача 10a), а исключение обязано быть названным
// и проверяемым — то есть файлом в списке, а не строкой посреди `app.js`.

/** Стартовая модель: термореле на двух состояниях. */
export const SAMPLE = `// Термореле: греет, пока холодно, и ждёт, пока не остынет.
in temperature: u8;
out heater: bit;

const HOT := 24;
const COLD := 20;

start Heating {
    always {
        heater := 1;
    }

    ref Cooling: temperature >= HOT;
}

state Cooling {
    always {
        heater := 0;
    }

    ref Heating: temperature <= COLD;
}
`;
